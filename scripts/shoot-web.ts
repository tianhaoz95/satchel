// Screenshots of the web app (landing, docs, portal in demo mode).
import { chromium } from "playwright";
const base = process.argv[2] ?? "http://127.0.0.1:5181";
const out = process.argv[3] ?? "report/mvp/site/shots";
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1360, height: 860 }, deviceScaleFactor: 2 });
const p = await ctx.newPage();
p.on("pageerror", (e) => console.error("pageerror", e.message));
await p.goto(base);
await p.waitForSelector(".hero");
await p.screenshot({ path: `${out}/web-landing.png` });
await p.screenshot({ path: `${out}/web-landing-full.png`, fullPage: true });
await p.goto(`${base}/docs/security`);
await p.waitForSelector(".prose h1");
await p.screenshot({ path: `${out}/web-docs.png` });
await p.goto(`${base}/login`);
await p.screenshot({ path: `${out}/web-login.png` });
await p.fill("input[type=email]", "alex@example.com");
await p.click("button.primary");
await p.waitForURL("**/portal");
await p.fill("input[placeholder='Home NAS']", "Home NAS");
await p.fill("input[placeholder='alex']", "alex");
await p.click("form button.primary");
await p.waitForSelector(".setup");
await p.waitForTimeout(300);
await p.screenshot({ path: `${out}/web-portal.png`, fullPage: true });
const m = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 3, isMobile: true });
const mp = await m.newPage();
await mp.goto(base);
await mp.waitForSelector(".hero");
await mp.screenshot({ path: `${out}/web-landing-mobile.png` });
await b.close();
console.log("ok");
